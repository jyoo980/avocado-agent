"""Utilities for mutation testing."""

import hashlib
import os
import re
import secrets
from collections.abc import Sequence
from pathlib import Path

from tools.run_cbmc import RunCbmcResult

# 0 indicates success, 10 indicates failure, 124 indicates timeout.
_CBMC_RETURN_CODES_SUCCESS_FAILURE_TIMEOUT = frozenset({0, 10, 124})

# The infixes that mark a generated mutant source file, e.g., `foo__mutant_<run>_3.c`.
MUTANT_INFIX = "mutant"
CLAUSE_DROP_INFIX = "clause_drop"

# Matches the stem of a generated mutant source file: `<stem>__<infix>_[<run-token>_]<index>`.
# The run token is optional so that artifacts kept by older versions are matched too.
_MUTANT_ARTIFACT_STEM_RE = re.compile(
    rf"__(?:{MUTANT_INFIX}|{CLAUSE_DROP_INFIX})_(?:[0-9a-f]+_)?\d+$"
)


def is_mutant_artifact(path: Path) -> bool:
    """Return True iff the path names a mutant source file generated by mutation testing.

    Args:
        path (Path): The path to check.

    Returns:
        bool: True iff the path names a generated mutant source file.
    """
    return _MUTANT_ARTIFACT_STEM_RE.search(path.stem) is not None


def write_mutant_sources(
    source_path: Path, infix: str, mutant_sources: Sequence[str]
) -> list[Path]:
    """Write each mutant source to a new file next to `source_path`, and return the paths.

    Each file is named `<stem>__<infix>_<run-token>_<index><suffix>`, where the run token is
    random and shared by every file of this call, so concurrent runs on the same source do not
    collide. If that name would be too long, it is shortened; see `get_bounded_mutant_file_name`.
    Files are created exclusively: if a target path already exists, no existing file is
    overwritten, the files created by this call are removed, and `FileExistsError` is raised.

    Args:
        source_path (Path): The original source file; mutants are written in its directory.
        infix (str): The infix identifying the kind of mutant, e.g., `MUTANT_INFIX`.
        mutant_sources (Sequence[str]): The mutant sources, in order.

    Returns:
        list[Path]: The created paths, one per mutant source and in the same order. Only these
            paths were created by this call, so only these should be removed later.
    """
    run_token = secrets.token_hex(4)
    created: list[Path] = []
    try:
        for index, mutant_source in enumerate(mutant_sources):
            path = source_path.with_name(
                get_bounded_mutant_file_name(
                    source_path.stem, infix, run_token, index, source_path.suffix
                )
            )
            with path.open("x", encoding="utf-8") as f:
                created.append(path)
                f.write(mutant_source)
    except BaseException:
        for path in created:
            path.unlink(missing_ok=True)
        raise
    return created


# The per-component file name limit (in bytes) on common filesystems (ext4, APFS, NTFS, ...).
_MAX_FILE_NAME_BYTES = 255


def get_bounded_mutant_file_name(
    stem: str, marker: str, function: str, index: int, suffix: str
) -> str:
    """Return a mutant file name `<stem>__<marker>_<function>_<index><suffix>`, bounded in length.

    If the readable name would exceed the filesystem's per-component length limit, the function
    name is replaced by a short digest of the full (stem, function) pair, and the stem is truncated
    if needed. The name then stays bounded but is still distinct for each function and index. It
    always contains `__<marker>_`, so it still matches the patterns that `make clean-mutants`
    removes.

    Byte lengths are measured with `os.fsencode`, which counts name bytes the way the filesystem
    does. It uses surrogateescape, so basenames that are not valid UTF-8 do not raise.

    Args:
        stem (str): The stem of the original source file.
        marker (str): The mutant-kind marker, e.g. `mutant` or `clause_drop`.
        function (str): The function the mutant belongs to.
        index (int): The index of the mutant.
        suffix (str): The suffix of the original source file, e.g. `.c`.

    Returns:
        str: The mutant file name (a single path component).
    """
    name = f"{stem}__{marker}_{function}_{index}{suffix}"
    if len(os.fsencode(name)) <= _MAX_FILE_NAME_BYTES:
        return name

    # Too long: replace the function name with a digest of the full (stem, function) pair, so that
    # truncating the stem cannot make two distinct inputs collide.
    digest = hashlib.sha256(os.fsencode(f"{stem}\0{function}")).hexdigest()[:16]
    tail = f"__{marker}_{digest}_{index}{suffix}"
    stem_budget = max(0, _MAX_FILE_NAME_BYTES - len(os.fsencode(tail)))
    # Truncate at character boundaries so that a multibyte character is never split.
    truncated_stem = ""
    used = 0
    for char in stem:
        char_bytes = len(os.fsencode(char))
        if used + char_bytes > stem_budget:
            break
        truncated_stem += char
        used += char_bytes
    return truncated_stem + tail


def is_valid_mutation_candidate(run_cbmc_result: RunCbmcResult) -> bool:
    """Return True iff the function under verification can serve as a mutation-testing baseline.

    A valid candidate is one for which CBMC ran end-to-end and verified the function — i.e.,
    every pipeline step completed without failure or timeout and CBMC reported success.
    Mutants are scored against this baseline, so anything weaker (compile/instrument failure,
    timeout, or a real verification failure) makes the candidate unusable.

    Args:
        run_cbmc_result (RunCbmcResult): The CBMC run result for the candidate function.

    Returns:
        bool: True iff the candidate verifies successfully.
    """
    return run_cbmc_result.is_function_verified


def absolute_path_without_resolving(file_path: str) -> Path:
    """Return an absolute version of `file_path` that neither follows symlinks nor collapses `..`.

    Unlike `Path.resolve`, symlinks are not followed, so a mutant written next to a symlinked file
    sees the same quoted `#include`s as the file itself. Unlike `os.path.abspath`, `..` segments are
    kept: collapsing them lexically could name a different file than the kernel resolves (e.g.,
    `link/../f.c` where `link` is a symlinked directory).

    Args:
        file_path (str): A relative or absolute path.

    Returns:
        Path: An absolute path that the kernel resolves to the same file as `file_path`.
    """
    # Joining with `/` yields `file_path` unchanged when it is already absolute, and (unlike
    # `os.path.abspath`) pathlib never collapses `..` segments.
    return Path.cwd() / file_path


def write_new_file(path: Path, text: str) -> None:
    """Write `text` to `path`, which must not already exist.

    Args:
        path (Path): The file to create.
        text (str): The contents of the file.

    Raises:
        FileExistsError: If `path` already exists; the existing file is left untouched.
    """
    with path.open("x", encoding="utf-8") as f:
        f.write(text)


def check_expected_cbmc_return_code(return_code: int):
    """Check whether the return code is indicates a verification success, failure, or timeout.

    Args:
        return_code (int): The return code to check for verification success, failure, or timeout.
    """
    if return_code not in _CBMC_RETURN_CODES_SUCCESS_FAILURE_TIMEOUT:
        msg = (
            f"Unexpected CBMC return code: {return_code}. "
            "See: https://diffblue.github.io/cbmc/exit__codes_8h.html"
        )
        raise RuntimeError(msg)


def get_files_with_extension(path_str: str, extension: str) -> list[Path]:
    """Return the path(s) to the file(s) with the given extension at the path.

    If the path resolves to a directory, recursively collect files, skipping generated mutant
    sources (see `is_mutant_artifact()`), such as those retained by `--keep-artifacts`.

    Args:
        path_str (str): Path to a file or directory.
        extension (str): The extension to match files on.

    Returns:
        list[Path]: The path(s) to the file(s) with the given extension at the path.
    """
    path = Path(path_str)
    if not path.exists():
        msg = f"{path} does not exist; double-check for full or relative paths"
        raise RuntimeError(msg)
    if path.is_dir():
        return sorted(p for p in path.rglob(f"*{extension}") if not is_mutant_artifact(p))
    return [path] if path.suffix == extension else []
